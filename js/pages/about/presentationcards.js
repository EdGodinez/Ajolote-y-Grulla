export function renderTeamCards() {
    const container = document.getElementById("about-team");
    if (!container) return;

    let allCardsHTML = `;
        <div class="section-header-team">
                <h2 class="section-title-main">Nuestro equipo</h2>
                <p class="section-subtitle-main">Conoce a las personas detrás del proyecto.</p>
            </div>
        `;

    presentationcards.forEach(miembro => {
        let skillsHTML = '';
        miembro.Habilidad.forEach(habilidad => {
            skillsHTML += `<span class="skill-tag" style="background-color: ${habilidad.color}">${habilidad.habilidad}</span>`;
        });

        const linkedinUrl = miembro.linkedin.startsWith('http') 
            ? miembro.linkedin 
            : `https://${miembro.linkedin}`;

        allCardsHTML += `
            <article class="tarjeta-equipo">
                <div class="card-left">
                    <img src="${miembro.foto}" alt="Avatar de ${miembro.nombre}" class="avatar">
                    <span class="team-badge">Bit Busters • Equipo 4</span>
                </div>
                <div class="card-right">
                    <div class="card-info-top">
                        <h2 class="card-name">${miembro.nombre}</h2>
                        <h3 class="card-role">${miembro.rol}</h3>
                        <p class="card-description">${miembro.descripcion}</p>
                        <div class="skills-container">
                            ${skillsHTML}
                        </div>
                    </div>

                    <div class="social-links">
                        <a href="${miembro.github}" target="_blank" rel="noopener noreferrer" title="GitHub">
                            <i class="bi bi-github"></i>
                            <span>GitHub</span>
                        </a>
                        <a href="${linkedinUrl}" target="_blank" rel="noopener noreferrer" title="LinkedIn">
                            <i class="bi bi-linkedin"></i>
                            <span>LinkedIn</span>
                        </a>
                        <a href="mailto:${miembro.correoelectronico}" title="${miembro.correoelectronico}">
                            <i class="bi bi-envelope-fill"></i>
                            <span>Correo</span>
                        </a>
                    </div>
                </div>
            </article>
        `;
    });

    allCardsHTML += `
        <article class="tarjeta-equipo tarjeta-foto-final">
            <img src="assets/images/bitbusters.jpeg" alt="Equipo Bit Busters">
        </article>
    `;

    container.innerHTML = allCardsHTML;
}

export const renderTeam = renderTeamCards;

document.addEventListener('DOMContentLoaded', renderTeamCards);
window.addEventListener('load', renderTeamCards);